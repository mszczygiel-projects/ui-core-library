export const GENERATED_NOTICE =
  'Generated by ui-core-foundations from the Figma variables. Do not edit.';

/**
 * The cascade layer of the tokens. It comes after Tailwind's layers, whose `theme` declares
 * defaults under names the tokens share, such as `--font-mono`. A consumer's declaration outside
 * any layer wins over it wherever it is imported.
 */
export const TOKENS_LAYER = 'ui-core-tokens';

/**
 * The order of the cascade layers, which every stylesheet of the library declares first, so that
 * it holds whichever file a page imports first, with or without Tailwind.
 */
export const LAYER_ORDER = `@layer theme, base, components, utilities, ${TOKENS_LAYER};`;

/** Something odd that still produces usable CSS; the build reports it and carries on. */
export interface EmitWarning {
  readonly rule: 'unpaired-line-height' | 'unmapped-mode';
  readonly message: string;
}

export interface CssOptions {
  /** The width, in pixels, from which the Desktop values of Sizes apply. */
  readonly breakpointPx: number;
  /** Mirror a dark Themes mode onto `prefers-color-scheme: dark`. */
  readonly autoDarkMode: boolean;
}

const SURFACE_MODE_SELECTOR: Readonly<Record<string, string>> = {
  Default: ':root',
  Subtle: '[data-surface="subtle"]',
  Inverse: '[data-surface="inverse"]',
  Primary: '[data-surface="primary"]',
};

/** Composite shadows: a shape from Primitives Shadows with one of its colours. */
const SHADOWS: readonly (readonly [name: string, shape: string, color: string])[] = [
  ['--shadow-2xs', '2xs', 'soft'],
  ['--shadow-xs', 'xs', 'soft'],
  ['--shadow-sm', 'sm', 'default'],
  ['--shadow-md', 'md', 'default'],
  ['--shadow-lg', 'lg', 'default'],
  ['--shadow-xl', 'xl', 'default'],
  ['--shadow-2xl', '2xl', 'strong'],
];

const INSET_SHADOWS: readonly (readonly [name: string, shape: string, color: string])[] = [
  ['--inset-shadow-2xs', '2xs', 'soft'],
  ['--inset-shadow-xs', 'xs', 'soft'],
  ['--inset-shadow-sm', 'sm', 'soft'],
];

/** A composite shadow: the custom properties of its shape and of its colour. */
export interface CompositeShadow {
  readonly name: string;
  readonly shape: string;
  readonly color: string;
}

/** The composite shadows, shared by tokens.css, the Tailwind theme and the manifest. */
export function compositeShadows(): CompositeShadow[] {
  return [
    ...SHADOWS.map(([name, shape, color]) => ({
      name,
      shape: `--shadow-shape-${shape}`,
      color: `--shadow-color-${color}`,
    })),
    ...INSET_SHADOWS.map(([name, shape, color]) => ({
      name,
      shape: `--inset-shadow-shape-${shape}`,
      color: `--shadow-color-${color}`,
    })),
  ];
}

export function shadowDeclarations(): string[] {
  return compositeShadows().map(({ name, shape, color }) => {
    return `  ${name}: var(${shape}) var(${color});`;
  });
}

/**
 * The attributes that choose a Themes mode: `[data-theme="dark"]` for a scheme of
 * the base brand, `[data-brand="red"]` and `[data-brand="red"][data-theme="dark"]` for a further
 * brand. A mode diffs against the base mode, so the more specific selector of a brand's dark
 * scheme wins over the plain dark scheme on the same element.
 */
function themeAttributes(mode: string): string {
  const { brand, scheme } = themeModeParts(mode);
  if (brand === null) {
    return `[data-theme="${scheme ?? modeSlug(mode)}"]`;
  }
  return scheme === 'dark'
    ? `[data-brand="${brand}"][data-theme="dark"]`
    : `[data-brand="${brand}"]`;
}

/**
 * The selectors of a theme mode. The base mode answers to `:root` and to its own attribute, so
 * a page can pin it on a dark-mode system. Every mode also covers nested
 * `[data-surface="default"]` containers, which reset the surface back to the page theme.
 */
export function themeModeSelector(mode: string, isBase: boolean): string {
  if (isBase) {
    return `:root,\n${themeAttributes(mode)},\n[data-surface="default"]`;
  }
  const attributes = themeAttributes(mode);
  return `${attributes},\n${attributes} [data-surface="default"]`;
}

/**
 * Where a dark mode applies by the system setting: on a root that chose no theme, and for a
 * further brand, on its root that chose no theme.
 */
function systemDarkSelector(mode: string): string {
  const { brand } = themeModeParts(mode);
  const root =
    brand === null ? ':root:not([data-theme])' : `[data-brand="${brand}"]:not([data-theme])`;
  return `${root},\n  ${root} [data-surface="default"]`;
}

function surfaceModeSelector(mode: string): string {
  return SURFACE_MODE_SELECTOR[mode] ?? `[data-surface="${modeSlug(mode)}"]`;
}

/** The base density names its own attribute as well as `:root`, so a nested container can reset to it. */
function densitySelector(density: string | null, single: boolean): string {
  if (density === null) {
    return single ? ':root' : `:root,\n[data-density="${BASE_DENSITY}"]`;
  }
  return `[data-density="${density}"]`;
}

/** The known modes first, in their usual order, then any mode a client's file adds. */
function orderModes(modes: readonly string[], known: readonly string[]): string[] {
  return [
    ...known.filter((mode) => modes.includes(mode)),
    ...modes.filter((mode) => !known.includes(mode)),
  ];
}

function isPresent<T>(value: T | null): value is T {
  return value !== null;
}

/**
 * A line height as a ratio of its font size, so it scales with the text it belongs to. Without
 * a font size to pair with, it assumes the 16px root.
 */
function formatLineHeight(
  token: Token,
  mode: string | null,
  registry: Registry,
  warnings: EmitWarning[],
): string {
  const pair = findFontSizePair(token, registry);
  const lineHeight = resolveNumber(token, mode, registry);
  if (lineHeight === null || lineHeight === 0) {
    return '0';
  }
  const lineHeightRem = cleanNumber(lineHeight / 16);
  if (pair === null) {
    warnings.push({
      rule: 'unpaired-line-height',
      message: `${tokenId(token.collection, token.path)} has no font size to pair with; it assumes 16px`,
    });
    return `calc(${lineHeightRem} / 1)`;
  }
  const fontSize = resolveNumber(pair, mode, registry);
  if (fontSize === null || fontSize === 0) {
    return `calc(${lineHeightRem} / 1)`;
  }
  return `calc(${lineHeightRem} / ${cleanNumber(fontSize / 16)})`;
}

/** One value as CSS: an alias becomes the `var()` of its target, a raw value gets its unit. */
export function valueToCss(
  token: Token,
  raw: Primitive,
  mode: string | null,
  registry: Registry,
  warnings: EmitWarning[],
): string {
  if (isAlias(raw)) {
    const target = parseAlias(raw);
    if (target === null) {
      return 'initial';
    }
    const reference = `var(${cssVarName(target.collection, normalizedPath(target.path))})`;
    const source =
      pathCategory(token.path) === 'line-height' ? aliasTarget(raw, registry) : undefined;
    // Only a line height reaches CSS as a ratio of its own font size. Any other length, such as a
    // font size, is already the designed line height.
    if (source !== undefined && pathCategory(source.path) === 'line-height') {
      const ownPair = findFontSizePair(token, registry);
      const sourcePair = findFontSizePair(source, registry);
      const ownSize = ownPair === null ? 16 : resolveNumber(ownPair, mode, registry);
      const sourceSize = sourcePair === null ? 16 : resolveNumber(sourcePair, mode, registry);
      // Figma aliases a length; CSS aliases a ratio. Keep the alias, correcting its basis.
      if (ownSize !== null && ownSize > 0 && sourceSize !== null && sourceSize !== ownSize) {
        return `calc(${reference} * ${cleanNumber(sourceSize)} / ${cleanNumber(ownSize)})`;
      }
    }
    return reference;
  }
  switch (token.type) {
    case 'color':
      return String(raw);
    case 'number':
      if (pathCategory(token.path) === 'line-height') {
        return formatLineHeight(token, mode, registry, warnings);
      }
      return typeof raw === 'number' ? formatNumber(token.path, raw) : String(raw);
    case 'string':
      return formatString(token.path, String(raw));
    case 'boolean':
      return formatBoolean(token.path, typeof raw === 'boolean' ? raw : String(raw) === 'true');
  }
}

/**
 * A declaration, or null when it would read `--x: var(--x)`. That happens where a semantic
 * collection aliases the token another one declares under the same name, as the Default surface
 * does with the theme; the theme's declaration already covers it.
 */
function declaration(
  token: Token,
  raw: Primitive,
  mode: string | null,
  registry: Registry,
  warnings: EmitWarning[],
): string | null {
  const name = cssVarName(token.collection, token.path);
  const value = valueToCss(token, raw, mode, registry, warnings);
  return value === `var(${name})` ? null : `  ${name}: ${value};`;
}

function block(comment: string, selector: string, lines: readonly string[]): string[] {
  return [`/* === ${comment} === */\n${selector} {`, ...lines, '}\n'];
}

/** A block wrapped in a media query; its declarations are indented one level further. */
function mediaBlock(
  comment: string,
  query: string,
  selector: string,
  lines: readonly string[],
): string[] {
  return [
    `/* === ${comment} === */\n@media ${query} {\n  ${selector} {`,
    ...lines.map((line) => `  ${line}`),
    '  }\n}\n',
  ];
}

/**
 * Reverse aliases inside Themes: target → the tokens that alias it. A theme mode re-declares
 * them alongside the tokens they follow.
 */
function themeDependents(themes: readonly Token[]): Map<string, Set<string>> {
  const keys = new Set(themes.map((t) => tokenKey(t.collection, normalizedPath(t.path))));
  const dependents = new Map<string, Set<string>>();
  for (const theme of themes) {
    const from = tokenKey(theme.collection, normalizedPath(theme.path));
    for (const { raw } of valuesByMode(theme)) {
      const target = isAlias(raw) ? parseAlias(raw) : null;
      if (target?.collection !== 'Themes') {
        continue;
      }
      const key = tokenKey(target.collection, normalizedPath(target.path));
      if (keys.has(key)) {
        dependents.set(key, (dependents.get(key) ?? new Set<string>()).add(from));
      }
    }
  }
  return dependents;
}

/**
 * The theme tokens a mode re-declares: those whose value differs from the base mode, and every
 * alias that depends on one of them.
 */
function tokensForThemeMode(
  themes: readonly Token[],
  mode: string,
  baseMode: string,
  dependents: ReadonlyMap<string, ReadonlySet<string>>,
): Token[] {
  const changed = new Set(
    themes
      .filter((t) => {
        return (
          isModeValues(t.value) &&
          mode in t.value &&
          baseMode in t.value &&
          t.value[mode] !== t.value[baseMode]
        );
      })
      .map((t) => tokenKey(t.collection, normalizedPath(t.path))),
  );
  const queue = [...changed];
  for (let key = queue.shift(); key !== undefined; key = queue.shift()) {
    for (const dependent of dependents.get(key) ?? []) {
      if (!changed.has(dependent)) {
        changed.add(dependent);
        queue.push(dependent);
      }
    }
  }
  return themes.filter((t) => changed.has(tokenKey(t.collection, normalizedPath(t.path))));
}

/**
 * tokens.css: every token as a CSS custom property, in the scopes where its value can change.
 *
 * A custom property that holds `var()` is substituted on the element it is declared on, and
 * descendants inherit the substituted result. A role declared only on `:root` would therefore
 * freeze at its `:root` value and ignore a `[data-surface]` or `[data-density]` container below.
 * That is why component colours are declared again in every theme and surface scope, and the
 * dimensions that reach Sizes in every density scope.
 */
export function emitTokensCss(
  tokens: readonly Token[],
  registry: Registry,
  options: CssOptions,
): { css: string; warnings: EmitWarning[] } {
  const warnings: EmitWarning[] = [];
  const inCollection = (collection: Collection) =>
    tokens.filter((t) => t.collection === collection);
  const line = (token: Token, raw: Primitive, mode: string | null) =>
    declaration(token, raw, mode, registry, warnings);
  const valueIn = (token: Token, mode: string) => {
    const values = valuesByMode(token);
    return values.find((v) => v.mode === mode) ?? values[0];
  };

  const chunks: string[] = [
    `/* ${GENERATED_NOTICE} */\n`,
    `${LAYER_ORDER}\n`,
    `@layer ${TOKENS_LAYER} {\n`,
  ];

  for (const [comment, collection] of [
    ['Primitives — Sizes', 'Primitives Sizes'],
    ['Primitives — Colors', 'Primitives Colors'],
    ['Primitives — Motion', 'Primitives Motions'],
    ['Primitives — Shadows', 'Primitives Shadows'],
  ] as const) {
    // A primitive is never self-referential, so every one of them is declared.
    const lines = inCollection(collection).flatMap((t) => {
      const raw = valuesByMode(t)[0]?.raw;
      if (raw === undefined) {
        return [];
      }
      return [
        `  ${cssVarName(t.collection, t.path)}: ${valueToCss(t, raw, null, registry, warnings)};`,
      ];
    });
    chunks.push(...block(comment, ':root', lines));
  }

  chunks.push(...block('Shadows (composite)', ':root', shadowDeclarations()));

  // Themes: the base mode lands on :root, every other mode on its attributes.
  const themes = inCollection('Themes');
  const themeModes = collectModes(themes);
  const baseThemeMode = baseModeOf(themeModes) ?? 'Light';
  const dependents = themeDependents(themes);
  const tokensByMode = new Map(
    themeModes
      .filter((mode) => mode !== baseThemeMode)
      .map((mode) => [mode, tokensForThemeMode(themes, mode, baseThemeMode, dependents)] as const),
  );
  const varying = new Set([...tokensByMode.values()].flat());
  // Only colours follow the surface, so only they, and whatever changes with the mode, need the
  // reset scopes. Anything else stays on :root alone, like a primitive, so a client can override
  // a brand value there and reach the whole page, `[data-surface="default"]` regions included.
  const followsScope = (t: Token) => t.type === 'color' || varying.has(t);
  const baseLine = (t: Token) =>
    line(t, rawForMode(t, baseThemeMode, baseThemeMode), baseThemeMode);
  const baseLines = themes.filter(followsScope).map(baseLine).filter(isPresent);
  if (baseLines.length > 0) {
    chunks.push(...block('Themes', themeModeSelector(baseThemeMode, true), baseLines));
  }
  const rootLines = themes
    .filter((t) => !followsScope(t))
    .map(baseLine)
    .filter(isPresent);
  if (rootLines.length > 0) {
    chunks.push(...block('Themes — the same in every mode', ':root', rootLines));
  }
  for (const [mode, modeTokens] of tokensByMode) {
    const lines = modeTokens
      .map((t) => line(t, rawForMode(t, mode, baseThemeMode), mode))
      .filter(isPresent);
    if (lines.length === 0) {
      continue;
    }
    chunks.push(...block(`Themes (${mode})`, themeModeSelector(mode, false), lines));
    // `:not([data-theme])` keeps the system setting from overriding a chosen theme.
    if (options.autoDarkMode && themeModeParts(mode).scheme === 'dark') {
      chunks.push(
        ...mediaBlock(
          `Themes (${mode} — system preference)`,
          '(prefers-color-scheme: dark)',
          systemDarkSelector(mode),
          lines,
        ),
      );
    }
  }

  // Surfaces: one block per mode. The Default surface lands on :root, where a value that
  // reaches Color is substituted and inherited already resolved, so its theme-dependent lines
  // are declared again in every theme scope.
  const surfaces = inCollection('Surfaces');
  const surfaceModes = orderModes(collectModes(surfaces), Object.keys(SURFACE_MODE_SELECTOR));
  for (const mode of surfaceModes) {
    const selector = surfaceModeSelector(mode);
    const lines: string[] = [];
    const themeDependentLines: string[] = [];
    for (const t of surfaces) {
      const entry = valueIn(t, mode);
      const declared = entry === undefined ? null : line(t, entry.raw, mode);
      if (declared === null) {
        continue;
      }
      lines.push(declared);
      if (dependsOnCollection(t, 'Themes', registry)) {
        themeDependentLines.push(declared);
      }
    }
    if (lines.length === 0) {
      continue;
    }
    if (selector !== ':root') {
      chunks.push(...block(`Surfaces (${mode})`, selector, lines));
      continue;
    }
    chunks.push(...block(`Surfaces (${mode})`, themeModeSelector(baseThemeMode, true), lines));
    for (const themeMode of themeModes) {
      if (themeMode !== baseThemeMode && themeDependentLines.length > 0) {
        chunks.push(
          ...block(
            `Surfaces (${mode} — ${themeMode})`,
            themeModeSelector(themeMode, false),
            themeDependentLines,
          ),
        );
      }
    }
  }

  // Sizes: one block per density, with the base screen's values, and the wide screen's values in
  // a media query inside each. Every density scope declares every Sizes token, so a
  // nested container never inherits a value resolved for another density.
  const sizes = inCollection('Sizes');
  const sizeModes = collectModes(sizes).map((mode) => ({ mode, ...sizesModeParts(mode) }));
  for (const { mode, screen } of sizeModes) {
    if (screen !== BASE_SCREEN && screen !== WIDE_SCREEN) {
      warnings.push({
        rule: 'unmapped-mode',
        message: `Sizes mode "${mode}" names no known screen; only ${BASE_SCREEN} and ${WIDE_SCREEN} are emitted`,
      });
    }
  }
  const densities = [...new Set(sizeModes.map((m) => m.density))].sort((a, b) =>
    a === null ? -1 : b === null ? 1 : 0,
  );
  const single = densities.length <= 1;
  const sizeMode = (screen: string, density: string | null) =>
    sizeModes.find((m) => m.screen === screen && m.density === density)?.mode;
  const wideBlocks: string[][] = [];
  for (const density of densities.length > 0 ? densities : [null]) {
    const selector = densitySelector(density, single);
    const baseMode = sizeMode(BASE_SCREEN, density) ?? sizeModes[0]?.mode ?? null;
    const lines = sizes
      .map((t) => {
        const entry = baseMode === null ? valuesByMode(t)[0] : valueIn(t, baseMode);
        return entry === undefined ? null : line(t, entry.raw, entry.mode);
      })
      .filter(isPresent);
    if (lines.length > 0) {
      chunks.push(...block(`Sizes (${baseMode ?? 'single mode'})`, selector, lines));
    }
    const wideMode = sizeMode(WIDE_SCREEN, density);
    if (baseMode === null || wideMode === undefined) {
      continue;
    }
    const wide = sizes
      .filter((t) => {
        const base = valueIn(t, baseMode);
        const wide = valueIn(t, wideMode);
        return (
          base !== undefined &&
          wide !== undefined &&
          line(t, wide.raw, wideMode) !== line(t, base.raw, baseMode)
        );
      })
      .map((t) => {
        const entry = valueIn(t, wideMode);
        return entry === undefined ? null : line(t, entry.raw, wideMode);
      })
      .filter(isPresent);
    if (wide.length > 0) {
      wideBlocks.push(
        mediaBlock(
          `Sizes (${wideMode})`,
          `(min-width: ${toRem(options.breakpointPx)})`,
          selector,
          wide,
        ),
      );
    }
  }
  for (const wide of wideBlocks) {
    chunks.push(...wide);
  }

  // Components: every token is a single alias. Colours repeat in every theme and surface scope;
  // a dimension repeats in the density scopes only when it reaches Sizes.
  const colorLines: string[] = [];
  const staticDimensionLines: string[] = [];
  const sizedDimensions: Token[] = [];
  for (const t of inCollection('Components')) {
    const entry = valuesByMode(t)[0];
    const declared = entry === undefined ? null : line(t, entry.raw, entry.mode);
    if (declared === null) {
      continue;
    }
    const fontSizePair = findFontSizePair(t, registry);
    if (t.type === 'color') {
      colorLines.push(declared);
    } else if (
      dependsOnCollection(t, 'Sizes', registry) ||
      (fontSizePair !== null && dependsOnCollection(fontSizePair, 'Sizes', registry))
    ) {
      sizedDimensions.push(t);
    } else {
      staticDimensionLines.push(declared);
    }
  }
  if (staticDimensionLines.length > 0) {
    chunks.push(...block('Components — dimensions', ':root', staticDimensionLines));
  }
  if (sizedDimensions.length > 0) {
    const declarations = (mode: string | null) =>
      sizedDimensions
        .map((t) => {
          const entry = valuesByMode(t)[0];
          return entry === undefined ? null : line(t, entry.raw, mode);
        })
        .filter(isPresent);
    for (const density of densities.length > 0 ? densities : [null]) {
      const selector = densitySelector(density, single);
      const baseMode = sizeMode(BASE_SCREEN, density) ?? sizeModes[0]?.mode ?? null;
      const base = declarations(baseMode);
      chunks.push(...block('Components — dimensions (sizes)', selector, base));
      const wideMode = sizeMode(WIDE_SCREEN, density);
      if (wideMode !== undefined) {
        const wide = declarations(wideMode).filter((entry, index) => entry !== base[index]);
        if (wide.length > 0) {
          chunks.push(
            ...mediaBlock(
              `Components — dimensions (${wideMode})`,
              `(min-width: ${toRem(options.breakpointPx)})`,
              selector,
              wide,
            ),
          );
        }
      }
    }
  }
  if (colorLines.length > 0) {
    const scopes = [
      themeModeSelector(baseThemeMode, true),
      ...themeModes.filter((m) => m !== baseThemeMode).map((m) => themeModeSelector(m, false)),
      ...surfaceModes.map(surfaceModeSelector).filter((selector) => selector !== ':root'),
    ];
    for (const selector of scopes) {
      chunks.push(...block('Components', selector, colorLines));
    }
    if (options.autoDarkMode) {
      for (const mode of themeModes.filter((m) => themeModeParts(m).scheme === 'dark')) {
        chunks.push(
          ...mediaBlock(
            `Components (${mode} — system preference)`,
            '(prefers-color-scheme: dark)',
            systemDarkSelector(mode),
            colorLines,
          ),
        );
      }
    }
  }

  chunks.push('}\n');
  return { css: chunks.join('\n'), warnings };
}
