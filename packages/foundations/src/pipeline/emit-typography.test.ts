import { describe, expect, it } from 'vitest';

import { emitTypographyCss, findClassCollisions, textStyles } from './emit-typography.ts';
import { parseExports, readExports } from './parse.ts';
import { EXPORTS_DIR, token } from './tokens.fixture.ts';

const sizes = (
  path: string,
  value: string | number | boolean,
  type: 'number' | 'string' | 'boolean' = 'number',
) => token('Sizes', path, { Mobile: value, Desktop: value }, type);

const themes = (
  path: string,
  value: string | number | boolean,
  type: 'number' | 'string' | 'boolean' = 'number',
) => token('Themes', path, { Light: value, Dark: value }, type);

const body = [
  themes('typography/body/font-family', '{Themes.font.body}', 'string'),
  themes('typography/body/font-weight', '{Primitives Sizes.font-weight.normal}'),
  themes('typography/body/font-weight-strong', '{Primitives Sizes.font-weight.semibold}'),
  sizes('typography/body/font-size', '{Primitives Sizes.text.base}'),
  sizes('typography/body/line-height', '{Primitives Sizes.text.base-line-height}'),
  themes('typography/body/letter-spacing', '{Primitives Sizes.tracking.normal}', 'string'),
  sizes('typography/body/small/font-size', '{Primitives Sizes.text.sm}'),
  sizes('typography/body/small/line-height', '{Primitives Sizes.text.sm-line-height}'),
];

describe('textStyles', () => {
  it('makes one style per group with a font size, taking what it lacks from the group above', () => {
    expect(textStyles(body)).toEqual([
      {
        path: ['body'],
        className: 'ui-text-body',
        properties: {
          'font-family': '--typography-body-font-family',
          'font-size': '--typography-body-font-size',
          'font-weight': '--typography-body-font-weight',
          'line-height': '--typography-body-line-height',
          'letter-spacing': '--typography-body-letter-spacing',
        },
        strongWeight: '--typography-body-font-weight-strong',
        source: 'Sizes/typography/body/font-size',
      },
      {
        path: ['body', 'small'],
        className: 'ui-text-body-small',
        properties: {
          'font-family': '--typography-body-font-family',
          'font-size': '--typography-body-small-font-size',
          'font-weight': '--typography-body-font-weight',
          'line-height': '--typography-body-small-line-height',
          'letter-spacing': '--typography-body-letter-spacing',
        },
        strongWeight: '--typography-body-font-weight-strong',
        source: 'Sizes/typography/body/small/font-size',
      },
    ]);
  });

  it('skips a group without a font size and every token outside typography', () => {
    const link = themes(
      'typography/link/font-weight',
      '{Themes.typography.body.font-weight-strong}',
    );
    const label = sizes('control/label/font-size', '{Primitives Sizes.text.xs}');
    const component = token('Components', 'typography/badge/font-size', '{Sizes.x}', 'number');
    expect(textStyles([link, label, component])).toEqual([]);
  });

  it('never takes a property from a sibling group', () => {
    const caption = [
      sizes('typography/caption/font-size', '{Primitives Sizes.text.sm}'),
      themes('typography/eyebrow/text-uppercase', '{Themes.text-uppercase.eyebrow}', 'boolean'),
    ];
    expect(textStyles(caption)[0]?.properties).toEqual({
      'font-size': '--typography-caption-font-size',
    });
  });

  it('sets the case of a style from its text-uppercase flag', () => {
    const eyebrow = [
      sizes('typography/eyebrow/font-size', '{Primitives Sizes.text.xs}'),
      themes('typography/eyebrow/text-uppercase', '{Themes.text-uppercase.eyebrow}', 'boolean'),
    ];
    expect(textStyles(eyebrow)[0]?.properties).toEqual({
      'font-size': '--typography-eyebrow-font-size',
      'text-transform': '--typography-eyebrow-text-uppercase',
    });
  });
});

describe('findClassCollisions', () => {
  it('names the two groups that make one class', () => {
    const styles = textStyles([
      sizes('typography/body/small/font-size', 16),
      sizes('typography/body-small/font-size', 16),
    ]);
    expect(findClassCollisions(styles)).toEqual([
      'Sizes/typography/body/small/font-size and Sizes/typography/body-small/font-size both make the text style class .ui-text-body-small; rename one of them in Figma',
    ]);
  });
});

describe('emitTypographyCss', () => {
  const css = emitTypographyCss(textStyles(body));

  it('nests the rules in a layer inside components, behind the order of Tailwind', () => {
    expect(css).toMatch(
      /^\/\* Generated by ui-core-foundations .*\*\/\n\n@layer theme, base, components, utilities, ui-core-tokens;\n\n@layer components\.ui-core \{\n/,
    );
    expect(css.trimEnd().endsWith('}')).toBe(true);
  });

  it('declares each property the style sets, as the var() of its role', () => {
    expect(css).toContain(
      [
        '  .ui-text-body-small {',
        '    font-family: var(--typography-body-font-family);',
        '    font-size: var(--typography-body-small-font-size);',
        '    font-weight: var(--typography-body-font-weight);',
        '    line-height: var(--typography-body-small-line-height);',
        '    letter-spacing: var(--typography-body-letter-spacing);',
        '  }',
      ].join('\n'),
    );
  });

  it('gives strong and b the strong weight of the style', () => {
    expect(css).toContain(
      '  .ui-text-body :is(strong, b) {\n    font-weight: var(--typography-body-font-weight-strong);\n  }',
    );
  });
});

describe('the text styles of the library', () => {
  const styles = textStyles(parseExports(readExports(EXPORTS_DIR)));

  it('are the fifteen groups of typography roles', () => {
    expect(styles.map((style) => style.className)).toEqual([
      'ui-text-heading-display',
      'ui-text-heading-display-large',
      'ui-text-heading-title',
      'ui-text-heading-subtitle',
      'ui-text-heading-h1',
      'ui-text-heading-h2',
      'ui-text-heading-h3',
      'ui-text-heading-h4',
      'ui-text-heading-h5',
      'ui-text-heading-h6',
      'ui-text-body',
      'ui-text-body-small',
      'ui-text-body-large',
      'ui-text-caption',
      'ui-text-eyebrow',
    ]);
    expect(findClassCollisions(styles)).toEqual([]);
  });

  it('each set the font, size, weight, line height and letter spacing', () => {
    for (const style of styles) {
      expect(Object.keys(style.properties), style.className).toEqual(
        expect.arrayContaining([
          'font-family',
          'font-size',
          'font-weight',
          'line-height',
          'letter-spacing',
        ]),
      );
    }
  });

  it('set capitals only where the theme decides them, on captions and eyebrows', () => {
    const transformed = styles.filter((style) => style.properties['text-transform'] !== undefined);
    expect(transformed.map((style) => style.className)).toEqual([
      'ui-text-caption',
      'ui-text-eyebrow',
    ]);
  });

  it('give display text the regular weight and keep the strong one for strong text', () => {
    const display = styles.find((style) => style.className === 'ui-text-heading-display');
    expect(display?.properties['font-weight']).toBe('--typography-heading-display-font-weight');
    expect(display?.strongWeight).toBe('--typography-heading-display-font-weight-strong');
  });
});
