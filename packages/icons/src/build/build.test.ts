import { mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

import {
  buildDirectory,
  buildIcons,
  emitModule,
  emitPackage,
  missingRequired,
  PACKAGE_NAME,
  parseRequired,
} from './build.ts';
import { VIEW_BOX } from './svg.ts';

const FIGMA_DIR = join(import.meta.dirname, '../../figma');
const STRICT = { strict: true };

function filled(d: string): string {
  return `<svg width="24" height="24" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg"><path d="${d}" fill="#174BA0"/></svg>`;
}

const LINED = (d: string): string =>
  `<svg width="24" height="24" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg"><path d="${d}" stroke="#174BA0" stroke-width="1.5"/></svg>`;

describe('buildIcons', () => {
  it('builds the icons in the order of their names', () => {
    const { icons, errors } = buildIcons(
      [
        { name: 'plus', svg: filled('M21 12H3M12 21V3') },
        { name: 'chevron-down', svg: filled('M5 9l7 6') },
      ],
      STRICT,
    );
    expect(errors).toEqual([]);
    expect(icons.map((icon) => [icon.name, icon.exportName])).toEqual([
      ['chevron-down', 'iconChevronDown'],
      ['plus', 'iconPlus'],
    ]);
    expect(icons[0]?.svg).toContain('fill="currentColor"');
  });

  it('stops on a name that is not in kebab case, and renames nothing', () => {
    const { icons, errors } = buildIcons(
      [
        { name: 'plus', svg: filled('M21 12H3') },
        { name: 'Chevron_Down', svg: filled('M5 9l7 6') },
      ],
      STRICT,
    );
    expect(icons).toEqual([]);
    expect(errors).toEqual([
      'Chevron_Down.svg is not named in kebab case, like chevron-down.svg; rename the component icon/Chevron_Down in Figma',
    ]);
  });

  it('stops when two names would export the same constant', () => {
    const { errors } = buildIcons(
      [
        { name: 'arrow-2', svg: filled('M0 0') },
        { name: 'arrow2', svg: filled('M0 0') },
      ],
      STRICT,
    );
    expect(errors).toEqual([
      'arrow-2.svg and arrow2.svg would both export iconArrow2; rename one of them in Figma',
    ]);
  });

  it('stops on every icon that breaks a rule, and writes none', () => {
    const { icons, errors } = buildIcons(
      [
        { name: 'plus', svg: filled('M21 12H3') },
        { name: 'broken', svg: '<svg viewBox="0 0 24 24"><path></svg>' },
        { name: 'lined', svg: LINED('M0 0') },
      ],
      STRICT,
    );
    expect(icons).toEqual([]);
    expect(errors).toHaveLength(2);
    expect(errors[0]).toMatch(/^broken\.svg cannot be read/);
    expect(errors[1]).toMatch(/^lined\.svg draws with strokes/);
  });
});

describe('buildDirectory', () => {
  function withFiles(files: Record<string, string>, folders: readonly string[]): string {
    const dir = mkdtempSync(join(tmpdir(), 'icons-'));
    for (const [file, content] of Object.entries(files)) {
      writeFileSync(join(dir, file), content);
    }
    for (const folder of folders) {
      mkdirSync(join(dir, folder));
    }
    return dir;
  }

  it('builds every icon of a directory, and leaves hidden files alone', () => {
    const dir = withFiles({ 'plus.svg': filled('M21 12H3M12 21V3'), '.DS_Store': '' }, []);
    try {
      const { icons, errors } = buildDirectory(dir, STRICT);
      expect(errors).toEqual([]);
      expect(icons.map((icon) => icon.exportName)).toEqual(['iconPlus']);
    } finally {
      rmSync(dir, { recursive: true });
    }
  });

  it('stops on every other file, so no icon goes missing silently', () => {
    const dir = withFiles(
      { 'plus.svg': filled('M21 12H3'), 'Close.SVG': filled('M6 6L18 18'), 'notes.txt': '' },
      ['extra.svg'],
    );
    try {
      const { icons, errors } = buildDirectory(dir, STRICT);
      expect(icons).toEqual([]);
      expect(errors).toEqual(
        ['Close.SVG', 'extra.svg', 'notes.txt'].map(
          (file) =>
            `${file} is not an icon file; icons are SVG files named in kebab case, like chevron-down.svg`,
        ),
      );
    } finally {
      rmSync(dir, { recursive: true });
    }
  });
});

describe('emitModule', () => {
  it('exports one typed string per icon', () => {
    const { icons } = buildIcons([{ name: 'minus', svg: filled('M21 12H3') }], STRICT);
    expect(emitModule(icons)).toBe(
      [
        '// Generated by scripts/generate.ts from the SVG files in figma/. Do not edit.',
        '',
        '/** The `minus` icon of [Core] Icons. */',
        'export const iconMinus: string = "<svg xmlns=\\"http://www.w3.org/2000/svg\\" width=\\"1em\\" height=\\"1em\\" fill=\\"none\\" viewBox=\\"0 0 24 24\\"><path fill=\\"currentColor\\" d=\\"M21 12H3\\"/></svg>";',
        '',
      ].join('\n'),
    );
  });
});

describe('the icons of the library', () => {
  const { icons, errors } = buildDirectory(FIGMA_DIR, STRICT);

  it('follow every rule', () => {
    expect(errors).toEqual([]);
    expect(icons).toHaveLength(
      readdirSync(FIGMA_DIR).filter((file) => !file.startsWith('.')).length,
    );
    expect(icons.length).toBeGreaterThan(30);
  });

  it('are drawn on one grid, sized by the text and painted in currentColor', () => {
    for (const icon of icons) {
      expect(icon.svg, icon.name).toMatch(
        new RegExp(
          `^<svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" fill="none" viewBox="${VIEW_BOX}">`,
        ),
      );
      expect(icon.svg, icon.name).not.toMatch(/#[0-9a-f]{3,6}\b|\sid=|<title|<desc|style=/i);
      expect(icon.svg, icon.name).toContain('currentColor');
      expect(icon.svg, icon.name).not.toContain('stroke');
    }
  });
});

describe("a consumer's set", () => {
  const lined = LINED('M21 12H3');

  it('builds icons that break a design rule, with a warning', () => {
    const { icons, errors, warnings } = buildIcons([{ name: 'minus', svg: lined }], {
      strict: false,
    });
    expect(errors).toEqual([]);
    expect(icons.map((icon) => icon.exportName)).toEqual(['iconMinus']);
    expect(warnings).toEqual([expect.stringMatching(/^minus\.svg draws with strokes/)]);
  });

  it('still stops on anything but plain shapes', () => {
    const scripted = filled('M21 12H3').replace('</svg>', '<script>alert(1)</script></svg>');
    const { icons, errors } = buildIcons([{ name: 'minus', svg: scripted }], { strict: false });
    expect(icons).toEqual([]);
    expect(errors).toEqual([expect.stringMatching(/^minus\.svg contains <script>/)]);
  });

  it('names every required icon the set lacks', () => {
    const { icons } = buildIcons([{ name: 'minus', svg: filled('M21 12H3') }], STRICT);
    const required = parseRequired('# imported by the components\nminus\n\nclose\n');
    expect(required).toEqual(['minus', 'close']);
    expect(missingRequired(icons, required)).toEqual([
      expect.stringMatching(/^close\.svg is missing/),
    ]);
  });

  it('becomes a package with the name and exports of the library', () => {
    const { icons } = buildIcons([{ name: 'minus', svg: filled('M21 12H3') }], STRICT);
    const files = emitPackage(icons, '1.2.3');
    expect(JSON.parse(files['package.json'])).toMatchObject({
      name: PACKAGE_NAME,
      version: '1.2.3',
      type: 'module',
      sideEffects: false,
      exports: { '.': { types: './index.d.ts', default: './index.js' } },
    });
    expect(files['index.js']).toContain(
      `export const iconMinus = ${JSON.stringify(icons[0]?.svg)};`,
    );
    expect(files['index.d.ts']).toContain('export declare const iconMinus: string;');
  });
});
